// ============================================================================
// AccessControl_Explanation.swift
// ООП-модификаторы: open / public / internal / fileprivate / private,
// private(set), final, static / class, override, required, convenience
// Под КАЖДЫМ модификатором: "ЛУЧШЕ" — что выбирать, "ИЗБЕГАЙ" — чего не делать.
// ============================================================================
//
// Общее правило: ЧЕМ УЖЕ ДОСТУП, ТЕМ ЛУЧШЕ. Начинай с `private`, расширяй
// только когда реально нужно. Узкий доступ = меньше связей, проще рефакторинг,
// компилятор оптимизирует лучше (final/private -> статическая диспетчеризация).
//
// Типы в неймспейсе `AccessControlLesson`.
// ============================================================================

import Foundation

enum AccessControlLesson {

    // ========================================================================
    // ЧАСТЬ 1. УРОВНИ ДОСТУПА (от широкого к узкому)
    // ========================================================================

    // ------------------------------------------------------------------------
    // open — виден везде + можно наследовать и переопределять ИЗ ДРУГОГО модуля
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: только в библиотеках/SDK, где ты СОЗНАТЕЛЬНО даёшь точки
    //   расширения (UIKit: UIViewController — open). Документируй, что
    //   разрешено переопределять.
    // ИЗБЕГАЙ: в приложении (у приложения один модуль — open бессмыслен),
    //   и "на всякий случай": каждый open-метод — обещание поддерживать
    //   подкласс-контракт вечно (Fragile Base Class problem).
    open class BaseScreen {
        open func configure() {}                    // точка расширения
        public func render() { configure() }        // сам алгоритм закрыт (Template Method)
        public init() {}
    }

    // ------------------------------------------------------------------------
    // public — виден везде, но снаружи модуля НЕЛЬЗЯ наследовать/переопределять
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: публичный API модуля/пакета (Core, Networking, DesignSystem):
    //   протоколы, модели, фасады. Для public struct явно пиши `: Sendable`,
    //   явный `public init` (memberwise init остаётся internal!).
    // ИЗБЕГАЙ: делать public всё подряд — выставляешь реализацию наружу;
    //   public тип с внутренним (internal) полем-типом — ошибка компиляции.
    public struct PublicUser: Sendable {
        public let id: Int
        public let name: String
        public init(id: Int, name: String) { self.id = id; self.name = name }
    }

    // ------------------------------------------------------------------------
    // internal — виден внутри модуля (УРОВЕНЬ ПО УМОЛЧАНИЮ)
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: код приложения; детали модуля, нужные нескольким файлам, но не
    //   клиентам. Не пиши слово internal — это шум, оно и так по умолчанию.
    // ИЗБЕГАЙ: полагаться на него как на "защиту" внутри большого модуля —
    //   в монолите internal = почти public. Дроби на модули (SPM).
    struct InternalHelper { func run() {} }

    // ------------------------------------------------------------------------
    // fileprivate — виден внутри ФАЙЛА
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: когда два типа в одном файле тесно связаны (тип + его
    //   вспомогательный Builder/Reader), либо extension в том же файле
    //   нуждается в приватных данных другого типа.
    // ИЗБЕГАЙ: как замену private "чтобы заработало" — обычно признак, что
    //   тип надо вынести или переосмыслить границы.
    fileprivate struct FileScopedCache { var items: [String: Int] = [:] }

    // ------------------------------------------------------------------------
    // private — виден внутри объявления и его extension В ЭТОМ ЖЕ ФАЙЛЕ
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: ПО УМОЛЧАНИЮ для всех свойств, методов и вспомогательных типов
    //   внутри класса. Всё, что не часть контракта — private.
    // ИЗБЕГАЙ: открывать "для тестов": тестируй через публичное поведение;
    //   если нужен доступ — @testable import (открывает internal, не private).
    final class BankAccount {
        private var balanceMinor = 0                       // деталь реализации
        private let audit = FileScopedCache()

        func deposit(_ amount: Int) {
            guard isValid(amount) else { return }
            balanceMinor += amount
        }
        private func isValid(_ amount: Int) -> Bool { amount > 0 }   // вспомогательный
    }

    // ------------------------------------------------------------------------
    // private(set) / public private(set) — читать можно, писать нельзя снаружи
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: ДЛЯ СОСТОЯНИЯ ViewModel/сервиса: `private(set) var state`.
    //   Инкапсуляция: меняется только через методы -> инварианты защищены.
    //   Лучший баланс "наблюдаемо извне, управляется изнутри".
    // ИЗБЕГАЙ: открытый `var` с публичной записью "потому что быстрее" —
    //   потом не найдёшь, кто и где его изменил.
    final class Cart {
        public private(set) var items: [String] = []
        public private(set) var total = 0
        func add(_ name: String, price: Int) { items.append(name); total += price }
    }

    // ========================================================================
    // ЧАСТЬ 2. НАСЛЕДОВАНИЕ И ПЕРЕОПРЕДЕЛЕНИЕ
    // ========================================================================

    // ------------------------------------------------------------------------
    // final — запрещает наследование (класс) или переопределение (метод)
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: ПО УМОЛЧАНИЮ для классов: `final class`. Быстрее (статический
    //   вызов), безопаснее (нет неожиданных подклассов), Sendable-friendly.
    //   Снимай final, только когда есть реальный сценарий наследования.
    // ИЗБЕГАЙ: оставлять класс наследуемым "вдруг пригодится" — YAGNI;
    //   предпочти композицию и протоколы.
    final class Logger {
        func log(_ message: String) { print(message) }
    }

    // ------------------------------------------------------------------------
    // override — переопределение метода/свойства суперкласса (обязателен)
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: вызывай `super`, если базовое поведение нужно сохранить;
    //   соблюдай LSP (подкласс не должен ломать ожидания базового).
    // ИЗБЕГАЙ: переопределять, меняя смысл метода; глубокие иерархии (>2
    //   уровней) — хрупко, трудно читать.
    class Animal {
        let name: String
        init(name: String) { self.name = name }
        func speak() -> String { "..." }
    }
    final class Dog: Animal {
        override func speak() -> String { "Гав" }
    }
    final class Cat: Animal {
        override func speak() -> String { super.speak() + " Мяу" }  // расширили базовое
    }

    // ------------------------------------------------------------------------
    // static vs class — член типа
    // ------------------------------------------------------------------------
    // static: нельзя переопределить (неявно final). class: можно в подклассе.
    // ЛУЧШЕ: static — по умолчанию (константы, фабрики, утилиты); class —
    //   только когда фабрика/конфиг должна меняться в подклассах.
    // ИЗБЕГАЙ: изменяемый `static var` (глобальное состояние, гонки данных
    //   в Swift 6). Если нужен — actor / @MainActor / Mutex.
    class Theme {
        static let defaultSpacing = 8                        // константа типа
        class var accentName: String { "blue" }              // переопределяемо
    }
    final class DarkTheme: Theme {
        override class var accentName: String { "orange" }
    }

    // ------------------------------------------------------------------------
    // init-модификаторы: required / convenience / designated / failable
    // ------------------------------------------------------------------------
    // ЛУЧШЕ: один designated init, остальные convenience, делегирующие ему
    //   (меньше дублирования); failable `init?` для невалидного ввода;
    //   `required` — только когда фабрике/сериализации (NSCoding) нужен init
    //   у ВСЕХ подклассов.
    // ИЗБЕГАЙ: логики в init (сеть, IO) — init должен быть дешёвым и
    //   предсказуемым; для сложного — static-фабрика/async-метод.
    class Connection {
        let host: String
        let port: Int

        init(host: String, port: Int) {                       // designated
            self.host = host; self.port = port
        }
        convenience init() { self.init(host: "localhost", port: 8080) }   // делегирует
        convenience init?(url: String) {                                  // failable
            guard let c = URLComponents(string: url), let h = c.host else { return nil }
            self.init(host: h, port: c.port ?? 80)
        }
    }

    // ------------------------------------------------------------------------
    // ЧАСТЬ 3. ПЯТЬ ПРИНЦИПОВ ООП НА ПРАКТИКЕ
    // ------------------------------------------------------------------------
    // 1) ИНКАПСУЛЯЦИЯ  — private + private(set) + методы-команды
    // 2) НАСЛЕДОВАНИЕ  — для "является" (is-a), неглубокое, + final листья
    // 3) ПОЛИМОРФИЗМ   — через протоколы (лучше) и override (когда нужна база)
    // 4) АБСТРАКЦИЯ    — протокол скрывает реализацию (см. Protocols_Explanation)
    // 5) КОМПОЗИЦИЯ    — "имеет" (has-a) вместо наследования:
    //                    ЛУЧШЕ в 90% случаев ("favor composition over inheritance")

    static func polymorphismDemo() {
        let animals: [Animal] = [Dog(name: "Рекс"), Cat(name: "Мурка")]
        animals.forEach { print($0.name, $0.speak()) }       // динамическая диспетчеризация
    }

    // ========================================================================
    // ЧТО ЛУЧШЕ ВЫБРАТЬ: ШПАРГАЛКА
    // ========================================================================
    //  Свойство класса            -> private; наружу private(set) или метод
    //  Класс                      -> final class
    //  Тип данных                 -> struct (не класс)
    //  Публичный API модуля       -> public + явный public init
    //  Расширяемая библиотека     -> open (осознанно, с документацией)
    //  Общая логика нескольких типов -> протокол + default implementation
    //  Глобальное изменяемое состояние -> actor / @MainActor, не static var
    //  Тестируемость              -> протокол + DI, не открытие private
    //  Нужен доступ из тестов     -> @testable import (internal), не public

    static func run() {
        polymorphismDemo()
        let account = BankAccount()
        account.deposit(100)
        let cart = Cart()
        cart.add("Чай", price: 120)
        print(cart.total, DarkTheme.accentName, Connection(url: "https://a.uz:443")?.port ?? 0)
    }
}
